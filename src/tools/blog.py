import streamlit as st

from core.ui import TONES, page_header, render_output

SYSTEM = """あなたはSEOに精通したプロのWebライターです。
検索ユーザーの意図に最も的確に答え、Googleの「役に立つコンテンツ」（E-E-A-T：経験・専門性・権威性・信頼性）の基準を満たす記事を書きます。

## SEOのルール
- 最初に検索意図（ユーザーが本当に知りたいこと）を想定し、記事全体でそれに答える
- タイトルは32文字前後で、メインキーワードをできるだけ前半に入れる
- 冒頭（リード文）で読者の悩みに共感し、結論とこの記事でわかることを先に示す
- H2・H3見出しにメインキーワード・サブキーワード・関連語を自然に含め、見出しだけで内容がわかるようにする
- 関連キーワード・共起語を自然に使い、同じキーワードの不自然な繰り返しはしない
- 具体例・手順・比較・数字を入れて、独自性と網羅性を高める
- 事実と異なる統計・出典・数値をでっち上げない。裏付けが必要な箇所は【要確認：〇〇】と示す

## 書き手の体験・意見の扱い（最重要）
- ユーザーから体験談・意見が提供された場合は、それを書き手本人の一人称の体験として、最も説得力が増す箇所に具体的に織り込む
- 提供された体験の内容を誇張したり、提供されていないエピソードを作り話で足したりしない
- 体験談が提供されていない、または足りない箇所では、作り話をせず【ここに体験談：〇〇について書く（例：〜）】というプレースホルダーを置く。書き手が何を書けばよいかわかるよう、具体的なヒントを添える

## 出力形式
- Markdown形式（##, ###, 箇条書き, 太字）
- 記事の最後に「よくある質問（FAQ）」を2〜3問と、要点と次の行動を示す「まとめ」を入れる"""


def render() -> None:
    page_header("📝 ブログ記事作成", "SEOを意識した構成案や本文を作成します。あなたの体験談・意見を入れると、より評価されやすい記事になります。")

    topic = st.text_input("記事のテーマ *", placeholder="例: 在宅ワークで集中力を保つコツ")
    col1, col2 = st.columns(2)
    main_kw = col1.text_input("メインキーワード", placeholder="例: 在宅ワーク 集中力",
                              help="検索で上位を狙う一番重要なキーワード。タイトルや見出しに優先して入れます。")
    sub_kw = col2.text_input("サブキーワード（カンマ区切り）", placeholder="例: 集中できない, 習慣, 作業環境")
    reader = st.text_input("想定読者", placeholder="例: 在宅勤務を始めた20〜30代の会社員")

    experience = st.text_area(
        "✍️ あなたの体験談・意見（おすすめ）", height=150,
        placeholder="例: 在宅勤務を始めた頃は午後になると集中が切れていた。ポモドーロ・テクニック（25分作業＋5分休憩）を"
                    "試したら、1日の作業量が体感で1.5倍になった。ただしスマホは別の部屋に置かないと効果がなかった。",
        help="実際の経験・失敗談・数字・自分なりの意見を箇条書きでも書いてください。"
             "記事に一人称で織り込みます。空欄の場合は、体験談を入れるべき箇所に【ここに体験談】の目印が入ります。",
    )

    col1, col2, col3 = st.columns(3)
    mode = col1.selectbox("出力内容", ["構成案 + 本文", "構成案のみ", "本文のみ"])
    tone = col2.selectbox("文体・トーン", ["です・ます調"] + TONES + ["だ・である調"])
    length = col3.select_slider("文字数の目安", [1000, 2000, 3000, 5000, 8000], value=3000)

    notes = st.text_area("補足・盛り込みたい内容（任意）", height=80,
                         placeholder="例: 初心者でも今日からできる方法を中心にしたい")

    prompt = None
    if st.button("✨ 記事を作成", type="primary"):
        if not topic.strip():
            st.warning("記事のテーマを入力してください。")
        else:
            output_spec = {
                "構成案 + 本文": "1. メタディスクリプション（120文字前後）\n"
                                 "2. URLスラッグ案（英小文字とハイフン）\n"
                                 "3. 想定する検索意図（1〜2文）\n"
                                 "4. タイトル案3つ\n"
                                 "5. 見出し構成（H2/H3）\n"
                                 "6. 本文（1つ目のタイトル案を使用）",
                "構成案のみ": "1. 想定する検索意図（1〜2文）\n"
                             "2. タイトル案3つ\n"
                             "3. 見出し構成（H2/H3）と、各見出しで書く内容の要点\n"
                             "4. 書き手の体験談・意見を入れると効果的な見出しと、その理由",
                "本文のみ": "1. メタディスクリプション（120文字前後）\n"
                           "2. タイトル\n"
                           "3. 本文",
            }[mode]
            prompt = f"""以下の条件でSEOに強いブログ記事を作成してください。

## 条件
- テーマ: {topic}
- メインキーワード: {main_kw or "テーマから最適なものを判断"}
- サブキーワード: {sub_kw or "テーマから関連語を判断"}
- 想定読者: {reader or "テーマから判断"}
- 文体・トーン: {tone}
- 文字数の目安: 本文で約{length}字
- 補足: {notes or "なし"}

## 書き手の体験談・意見
{experience.strip() or "（提供なし。体験談を入れるべき箇所にプレースホルダーを置いてください）"}

## 出力する内容（この順番で）
{output_spec}"""

    render_output("blog", "ブログ記事作成", SYSTEM, prompt, filename="blog.md")
